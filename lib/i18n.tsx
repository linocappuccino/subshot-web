export type TranslationKey = keyof (typeof translations)["de"];

export { LANGUAGE_COOKIE };

export function readLanguageCookie(): Language {
  if (typeof document === "undefined") return "de";
  const match = document.cookie.match(new RegExp(`(?:^|; )${LANGUAGE_COOKIE}=([^;]*)`));
  const value = match ? decodeURIComponent(match[1]) : null;
  return value === "en" ? "en" : "de";
}

function writeLanguageCookie(lang: Language) {
  // 1 year, Lax (not cross-site, no need for None/Secure dance like the
  // share-link unlock cookie elsewhere in this app) — readable server-side
  // by layout.tsx via next/headers so Clerk's OWN dialog text (Sign out,
  // Manage account, etc.) can be localized at first paint too, not just
  // after a client-side fetch resolves.
  document.cookie = `${LANGUAGE_COOKIE}=${lang}; path=/; max-age=31536000; SameSite=Lax`;
}

